def explain(term: str) -> Term | None:
    """查一个术语的白话解释。查不到返回 None（不抛异常，方便渲染时兜底）。"""
    if not term:
        return None
    key = term.strip()
    if key in TERMS:
        return TERMS[key]
    low = key.lower()
    for name, entry in TERMS.items():
        if name.lower() == low:
            return entry
        if low in {a.lower() for a in entry.aliases}:
            return entry
    return None


def glossary_lines() -> list[str]:
    """把词典渲染成白话词条列表（供日报附录）。"""
    out: list[str] = []
    for name, entry in TERMS.items():
        line = f"{name}：{entry.plain}"
        if entry.how_to_read:
            line += f" 看的时候记住：{entry.how_to_read}"
        out.append(line)
    return out